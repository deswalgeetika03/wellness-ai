def main():

    parser = argparse.ArgumentParser(
        description="Wellness RAG query pipeline"
    )

    parser.add_argument(
        "--once",
        type=str,
        default=None,
        help="Answer one question and exit",
    )

    args = parser.parse_args()

    print("Loading Wellness RAG...")
    print(f"Embedding model: {EMBEDDING_MODEL}")
    print(f"Candidate pool: {CANDIDATE_K}")
    print(f"Final context chunks: {TOP_K}")
    print(f"Max chunks per source: {MAX_PER_SOURCE}")
    print(f"Granite model: {GRANITE_MODEL}")

    vector_db = get_vector_db()

    print("\nPipeline ready.\n")

    # --------------------------------------------------------
    # ONE QUESTION
    # --------------------------------------------------------

    if args.once:

        result = answer_query(
            vector_db,
            args.once,
        )

        print_result(result)
        return

    # --------------------------------------------------------
    # INTERACTIVE MODE
    # --------------------------------------------------------

    print(
        "Wellness RAG Bot\n"
        "Type a question or 'quit' to exit.\n"
    )

    while True:

        try:
            question = input("You: ").strip()

        except (EOFError, KeyboardInterrupt):

            print("\nExiting.")
            break

        if not question:
            continue

        if question.lower() in {
            "quit",
            "exit",
        }:
            break

        result = answer_query(
            vector_db,
            question,
        )

        print_result(result)


if __name__ == "__main__":
    sys.exit(main())