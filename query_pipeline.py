def print_result(result: dict):

    print("\n" + "=" * 60)
    print(f"ROUTE: {result['route']}")
    print("=" * 60)

    print("\nANSWER:")
    print(result["answer"])

    if result["sources"]:

        print("\nSOURCES:")

        for source in result["sources"]:
            print(
                f"  - {source['organization']}: "
                f"{source['title']}"
            )

    print()


